package at.htlle.pos;
//tool class to provide functionality to compute basic stuff

public class pocketCalculator {
    //basic claculator
    //+, -, *, /

    public static long addition(int numb1, int numb2){
        return (long)numb1 + numb2;
    }

    public static int  subtraction(int numb1, int numb2){
        return numb1 - numb2;
    }

    public static int multiplication(int numb1, int numb2){
        return numb1 * numb2;
    }

    public static int division(int numb1, int numb2){
        return numb1 / numb2;
    }


}
